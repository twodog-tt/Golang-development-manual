package mediaio

import "errors"

// Voice is a LOCAL control/playback model, not WebSocket/WebRTC protocol code.
// Session and generation IDs come from trusted transport acknowledgements.
type Voice struct {
	session, response, item string
	epoch                   uint64
	state                   string
	nextSeq                 int
	queued, played          int
	pending                 *Truncate
	seen                    map[string]bool
	sessions                map[string]bool
}
type Truncate struct {
	SessionID, ItemID, ResponseID string
	Epoch                         uint64
	ContentIndex                  int
	AudioEndMS                    int
}

func NewVoice(session string) (*Voice, error) {
	if session == "" {
		return nil, errors.New("session acknowledgement required")
	}
	return &Voice{session: session, epoch: 1, state: "ready", seen: map[string]bool{}, sessions: map[string]bool{session: true}}, nil
}
func (v *Voice) Epoch() uint64 { return v.epoch }
func (v *Voice) Start(response, item string) error {
	if v.state != "ready" || v.pending != nil || response == "" || item == "" || v.seen[response] || len(v.seen) >= 128 {
		return errors.New("voice session not ready")
	}
	v.seen[response] = true
	v.response = response
	v.item = item
	v.played = 0
	v.queued = 0
	v.nextSeq = 0
	v.state = "speaking"
	return nil
}
func (v *Voice) Append(session, response string, epoch uint64, sequence int, pcm []byte) error {
	if v.state != "speaking" || session != v.session || epoch != v.epoch || response != v.response || sequence != v.nextSeq || len(pcm) == 0 || len(pcm)%2 != 0 || len(pcm) > 48000 || v.queued > 96000-len(pcm) {
		return errors.New("stale, out-of-order or over-budget audio")
	}
	v.nextSeq++
	v.queued += len(pcm)
	return nil
}

// Played is called with actual consumed bytes, not received/generated byte counts.
func (v *Voice) Played(session, response string, epoch uint64, n int) error {
	if session != v.session || response != v.response || epoch != v.epoch || (v.state != "speaking" && v.state != "draining") || n <= 0 || n%2 != 0 || n > v.queued || v.played > 48000000-n {
		return errors.New("invalid playback acknowledgement")
	}
	v.queued -= n
	v.played += n
	if v.state == "draining" && v.queued == 0 {
		v.state = "ready"
	}
	return nil
}
func (v *Voice) Interrupt() (Truncate, error) {
	if v.state != "speaking" && v.state != "draining" {
		return Truncate{}, errors.New("nothing to interrupt")
	}
	v.queued = 0
	v.state = "awaiting-truncate"
	t := Truncate{SessionID: v.session, ItemID: v.item, ResponseID: v.response, Epoch: v.epoch, ContentIndex: 0, AudioEndMS: v.played / 48}
	v.pending = &t
	return t, nil
}
func (v *Voice) Acknowledge(t Truncate) error {
	if v.state != "awaiting-truncate" || v.pending == nil || *v.pending != t {
		return errors.New("wrong or stale truncate acknowledgement")
	}
	v.pending = nil
	v.state = "ready"
	return nil
}
func (v *Voice) Disconnect() { v.queued = 0; v.state = "disconnected" }

// Reconnect deliberately starts a NEW acknowledged session. There is no automatic
// resume/replay of old audio, tools or approvals. Same-ID recovery is unsupported.
func (v *Voice) Reconnect(newSession string) error {
	if v.state != "disconnected" || newSession == "" || v.sessions == nil || v.sessions[newSession] || len(v.sessions) >= 128 {
		return errors.New("fresh session required; old outcome unresolved")
	}
	v.sessions[newSession] = true
	v.session = newSession
	v.epoch++
	v.response = ""
	v.item = ""
	v.pending = nil
	v.seen = map[string]bool{}
	v.played = 0
	v.queued = 0
	v.nextSeq = 0
	v.state = "ready"
	return nil
}
func (v *Voice) Queued() int { return v.queued }

// Generated marks generation completion separately from actual playback completion.
func (v *Voice) Generated(session, response string, epoch uint64) error {
	if v.state != "speaking" || v.session != session || v.response != response || v.epoch != epoch {
		return errors.New("stale generation completion")
	}
	v.state = "draining"
	if v.queued == 0 {
		v.state = "ready"
	}
	return nil
}
